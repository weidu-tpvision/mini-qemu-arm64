// BENCHMARK: Interpreter vs. Statically Recompiled AOT
// ----------------------------------------------------------------------
async function benchmark() {
  const recompiler = new StaticRecompiler("bin/fib.elf");
  recompiler.recompile(true);

  const { runNative } = await import("../out/fib_recompiled.js");

  const ITERATIONS = 10000;
  console.log(`\n==========================================================================================`);
  console.log(`            PERFORMANCE BENCHMARK: Interpreter vs. Static Recompilation (AOT)             `);
  console.log(`            Running ${ITERATIONS.toLocaleString()} iterations of Fibonacci(10)            `);
  console.log(`==========================================================================================`);

  // 1. Benchmark Interpreter
  console.log(`Running in Mini-QEMU Interpreter (Fetch -> Decode -> Execute loop)...`);
  const emulator = new MiniQEMU();
  emulator.loadElf("bin/fib.elf");

  const startInterp = performance.now();
  let interpResult = 0;
  for (let i = 0; i < ITERATIONS; i++) {
    // Reset CPU for next run
    emulator.cpu.pc = 0x00400000n;
    emulator.cpu.halted = false;
    emulator.cycleCount = 0;
    interpResult = emulator.run(1000, false); // false = non-verbose
  }
  const endInterp = performance.now();
  const interpDurationMs = endInterp - startInterp;

  // 2. Benchmark Statically Recompiled Native Code (genuinely lifted from fib.elf)
  console.log(`Running in Statically Recompiled Native Code (runNative lifted from fib.elf)...`);
  const startAOT = performance.now();
  let aotResult = 0;
  for (let i = 0; i < ITERATIONS; i++) {
    aotResult = runNative();
  }
  const endAOT = performance.now();
  const aotDurationMs = endAOT - startAOT;

  console.log(`\n--- BENCHMARK RESULTS ---`);
  console.log(`Interpreter Result      : ${interpResult} in ${interpDurationMs.toFixed(2)} ms`);
  console.log(`Static Recompiled Result: ${aotResult} in ${aotDurationMs.toFixed(2)} ms`);
  console.log(`Speedup Factor          : ${(interpDurationMs / aotDurationMs).toFixed(1)}x FASTER with Static AOT!`);
  console.log(`==========================================================================================`);
}

if (typeof process !== "undefined" && process.argv && process.argv[1]?.endsWith("static_recompiler.js")) {
  benchmark();
}
