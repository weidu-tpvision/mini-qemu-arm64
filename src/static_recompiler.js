// static_recompiler.js - Ahead-Of-Time (AOT) Static Binary Recompiler (ARM64 -> JavaScript)
import fs from "fs";
import { Decoder, InstructionType, ConditionCode } from "./decoder.js";
import { ElfLoader } from "./elf_loader.js";
import { Memory } from "./memory.js";
import { MiniQEMU } from "./emulator.js";

export class StaticRecompiler {
  constructor(elfPathOrBuffer, name = null) {
    this.elfPath = typeof elfPathOrBuffer === "string" ? elfPathOrBuffer : (name || "binary.elf");
    this.memory = new Memory();
    this.entryPoint = ElfLoader.load(elfPathOrBuffer, this.memory);
  }

  // Decompile ARM64 instructions from the loaded ELF segment into native JS code
  recompile(writeFiles = true) {
    if (writeFiles) {
      console.log(`\n[Static Recompiler] Analyzing ARM64 binary for Ahead-Of-Time recompilation...`);
    }

    let pc = Number(this.entryPoint);
    const instructions = [];
    const codeSeg = (this.memory.segments || []).find(s => (s.flags & 1) !== 0) || (this.memory.segments || [])[0];
    const endPC = codeSeg ? (codeSeg.vaddr + codeSeg.filesz) : (pc + 256);

    // 1. Disassemble code segment (stopping at embedded data / unknown opcodes)
    const dataStartAddresses = new Set();
    while (pc + 4 <= endPC) {
      if (dataStartAddresses.has(pc)) break;
      const raw = this.memory.read32(pc);
      if (raw === 0) break;
      const decoded = Decoder.decode(raw);
      if (decoded.type === InstructionType.UNKNOWN) break;
      if (decoded.type === InstructionType.ADR) {
        const target = pc + decoded.offsetBytes;
        if (target > pc && target < endPC) {
          dataStartAddresses.add(target);
        }
      }
      instructions.push({ pc, raw, decoded });
      pc += 4;
      if (!codeSeg && decoded.type === InstructionType.SVC) break;
    }

    if (writeFiles) {
      console.log(`  Disassembled ${instructions.length} ARM64 instructions.`);
    }

    // 2. Generate Native Host Code
    const lines = [];
    lines.push("// Auto-generated by Mini-QEMU Static Recompiler (AOT)");
    lines.push("// Source binary: " + this.elfPath);
    lines.push("export function runNative() {");
    lines.push("  // 64-bit Virtual Registers (X0-X30) & Stack Pointer");
    lines.push("  const x = new BigUint64Array(31);");
    lines.push("  let sp = 0x00700000n;");
    lines.push("  let flagZ = false;");
    lines.push("  let flagN = false;");
    lines.push("");

    // Identify branch targets (labels) and backward loop ranges (targetPC -> count)
    const loopStarts = new Map();
    const funcTargets = new Set();
    for (const inst of instructions) {
      if (inst.decoded.type === InstructionType.B_COND || inst.decoded.type === InstructionType.B) {
        const targetPC = inst.pc + inst.decoded.offsetBytes;
        if (targetPC <= inst.pc) {
          loopStarts.set(targetPC, (loopStarts.get(targetPC) || 0) + 1);
        }
      } else if (inst.decoded.type === InstructionType.BL) {
        funcTargets.add(inst.pc + inst.decoded.offsetBytes);
      }
    }

    const regExpr = (r) => (r === 31 ? "0n" : `x[${r}]`);
    const spOrReg = (r) => (r === 31 ? "sp" : `x[${r}]`);

    // Generate structured JS code directly from the decoded ARM64 instructions
    let indentLevel = 1;
    const getIndent = () => "  ".repeat(indentLevel);

    for (const inst of instructions) {
      const { pc, decoded } = inst;
      const hexPC = `0x${pc.toString(16).padStart(8, "0")}`;

      if (funcTargets.has(pc)) {
        lines.push("");
        lines.push(`${getIndent()}// --- Subroutine entry at ${hexPC} ---`);
      }

      if (loopStarts.has(pc)) {
        const count = loopStarts.get(pc);
        for (let c = 0; c < count; c++) {
          lines.push(`${getIndent()}// Reconstructed backward-branch loop at ${hexPC}`);
          lines.push(`${getIndent()}do {`);
          indentLevel++;
        }
      }

      const indent = getIndent();

      switch (decoded.type) {
        case InstructionType.MOVZ:
        case InstructionType.MOVN:
          lines.push(`${indent}x[${decoded.rd}] = ${decoded.immValue}n; // ${decoded.disassembly} (${hexPC})`);
          break;

        case InstructionType.MOVK:
          lines.push(`${indent}x[${decoded.rd}] = (x[${decoded.rd}] & ~(0xffffn << ${decoded.shift}n)) | (${BigInt(decoded.imm16) << BigInt(decoded.shift)}n); // ${decoded.disassembly}`);
          break;

        case InstructionType.ADR:
          lines.push(`${indent}x[${decoded.rd}] = 0x${(pc + decoded.offsetBytes).toString(16)}n; // ${decoded.disassembly}`);
          break;

        case InstructionType.ADRP: {
          const pageBase = (pc & ~0xfff) + Number(decoded.offsetBytes);
          lines.push(`${indent}x[${decoded.rd}] = 0x${pageBase.toString(16)}n; // ${decoded.disassembly}`);
          break;
        }

        case InstructionType.ADD_IMM:
          lines.push(`${indent}${spOrReg(decoded.rd)} = ${spOrReg(decoded.rn)} + ${decoded.immValue}n; // ${decoded.disassembly}`);
          break;

        case InstructionType.SUB_IMM:
          lines.push(`${indent}${spOrReg(decoded.rd)} = ${spOrReg(decoded.rn)} - ${decoded.immValue}n; // ${decoded.disassembly}`);
          break;

        case InstructionType.ADD_REG:
          lines.push(`${indent}x[${decoded.rd}] = ${regExpr(decoded.rn)} + ${regExpr(decoded.rm)}; // ${decoded.disassembly}`);
          break;

        case InstructionType.SUB_REG:
          lines.push(`${indent}x[${decoded.rd}] = ${regExpr(decoded.rn)} - ${regExpr(decoded.rm)}; // ${decoded.disassembly}`);
          break;

        case InstructionType.MUL:
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(64, ${regExpr(decoded.rn)} * ${regExpr(decoded.rm)}); // ${decoded.disassembly}`);
          break;

        case InstructionType.MADD:
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(64, ${regExpr(decoded.ra)} + (${regExpr(decoded.rn)} * ${regExpr(decoded.rm)})); // ${decoded.disassembly}`);
          break;

        case InstructionType.MSUB:
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(64, ${regExpr(decoded.ra)} - (${regExpr(decoded.rn)} * ${regExpr(decoded.rm)})); // ${decoded.disassembly}`);
          break;

        case InstructionType.UDIV:
        case InstructionType.SDIV:
          lines.push(`${indent}x[${decoded.rd}] = ${regExpr(decoded.rm)} === 0n ? 0n : (${regExpr(decoded.rn)} / ${regExpr(decoded.rm)}); // ${decoded.disassembly}`);
          break;

        case InstructionType.LSL:
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(${decoded.sf === 0 ? 32 : 64}, ${regExpr(decoded.rn)} << (${regExpr(decoded.rm)} & ${decoded.sf === 0 ? 31 : 63}n)); // ${decoded.disassembly}`);
          break;

        case InstructionType.LSR:
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(${decoded.sf === 0 ? 32 : 64}, ${regExpr(decoded.rn)}) >> (${regExpr(decoded.rm)} & ${decoded.sf === 0 ? 31 : 63}n); // ${decoded.disassembly}`);
          break;

        case InstructionType.ASR:
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(${decoded.sf === 0 ? 32 : 64}, BigInt.asIntN(${decoded.sf === 0 ? 32 : 64}, ${regExpr(decoded.rn)}) >> (${regExpr(decoded.rm)} & ${decoded.sf === 0 ? 31 : 63}n)); // ${decoded.disassembly}`);
          break;

        case InstructionType.UBFM: {
          const bits = decoded.sf === 0 ? 32 : 64;
          const maxBit = bits - 1;
          if (decoded.imms !== maxBit && decoded.imms + 1 === decoded.immr) {
            const shift = bits - decoded.immr;
            lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(${bits}, ${regExpr(decoded.rn)} << ${shift}n); // ${decoded.disassembly}`);
          } else if (decoded.imms >= decoded.immr) {
            const width = decoded.imms - decoded.immr + 1;
            const mask = (1n << BigInt(width)) - 1n;
            const shifted = decoded.immr > 0 ? `(${regExpr(decoded.rn)} >> ${decoded.immr}n)` : regExpr(decoded.rn);
            lines.push(`${indent}x[${decoded.rd}] = ${shifted} & 0x${mask.toString(16)}n; // ${decoded.disassembly}`);
          } else {
            lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(${bits}, ${regExpr(decoded.rn)}); // ${decoded.disassembly}`);
          }
          break;
        }

        case InstructionType.SBFM: {
          const bits = decoded.sf === 0 ? 32 : 64;
          const width = Math.max(1, decoded.imms - decoded.immr + 1);
          const shifted = decoded.immr > 0 ? `(${regExpr(decoded.rn)} >> ${decoded.immr}n)` : regExpr(decoded.rn);
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(${bits}, BigInt.asIntN(${width}, ${shifted})); // ${decoded.disassembly}`);
          break;
        }

        case InstructionType.AND_REG:
          lines.push(`${indent}x[${decoded.rd}] = ${regExpr(decoded.rn)} & ${regExpr(decoded.rm)}; // ${decoded.disassembly}`);
          break;

        case InstructionType.EOR_REG:
          lines.push(`${indent}x[${decoded.rd}] = ${regExpr(decoded.rn)} ^ ${regExpr(decoded.rm)}; // ${decoded.disassembly}`);
          break;

        case InstructionType.MVN_REG:
          lines.push(`${indent}x[${decoded.rd}] = BigInt.asUintN(64, ~${regExpr(decoded.rm)}); // ${decoded.disassembly}`);
          break;

        case InstructionType.ORR_REG: {
          const rnVal = decoded.rn === 31 ? "0n" : `x[${decoded.rn}]`;
          const rmVal = decoded.rm === 31 ? "0n" : `x[${decoded.rm}]`;
          lines.push(`${indent}x[${decoded.rd}] = ${rnVal} | ${rmVal}; // ${decoded.disassembly}`);
          break;
        }

        case InstructionType.SUBS_IMM:
          lines.push(`${indent}{`);
          lines.push(`${indent}  const res = BigInt.asUintN(64, ${spOrReg(decoded.rn)} - ${decoded.immValue}n);`);
          if (decoded.rd !== 31) lines.push(`${indent}  x[${decoded.rd}] = res;`);
          lines.push(`${indent}  flagZ = (res === 0n);`);
          lines.push(`${indent}  flagN = ((res & (1n << 63n)) !== 0n);`);
          lines.push(`${indent}} // ${decoded.disassembly}`);
          break;

        case InstructionType.SUBS_REG:
          lines.push(`${indent}{`);
          lines.push(`${indent}  const res = BigInt.asUintN(64, ${regExpr(decoded.rn)} - ${regExpr(decoded.rm)});`);
          if (decoded.rd !== 31) lines.push(`${indent}  x[${decoded.rd}] = res;`);
          lines.push(`${indent}  flagZ = (res === 0n);`);
          lines.push(`${indent}  flagN = ((res & (1n << 63n)) !== 0n);`);
          lines.push(`${indent}} // ${decoded.disassembly}`);
          break;

        case InstructionType.STP:
        case InstructionType.LDP:
        case InstructionType.STR_IMM:
        case InstructionType.LDR_IMM:
        case InstructionType.STRW_IMM:
        case InstructionType.LDRW_IMM:
        case InstructionType.LDRSW_IMM:
        case InstructionType.STRH_IMM:
        case InstructionType.LDRH_IMM:
        case InstructionType.LDRSH_IMM:
        case InstructionType.STRB_IMM:
        case InstructionType.LDRB_IMM:
        case InstructionType.LDRSB_IMM:
          if ((decoded.preIndex || decoded.postIndex) && decoded.offsetBytes) {
            const sign = decoded.offsetBytes >= 0 ? "+" : "-";
            lines.push(`${indent}${spOrReg(decoded.rn)} = ${spOrReg(decoded.rn)} ${sign} ${Math.abs(decoded.offsetBytes)}n; // ${decoded.disassembly} (${hexPC})`);
          } else {
            lines.push(`${indent}/* Memory/Stack op (${hexPC}): ${decoded.disassembly} */`);
          }
          break;

        case InstructionType.CSEL: {
          const condExpr = decoded.cond === ConditionCode.EQ ? "flagZ" : "!flagZ";
          lines.push(`${indent}x[${decoded.rd}] = (${condExpr}) ? ${regExpr(decoded.rn)} : ${regExpr(decoded.rm)}; // ${decoded.disassembly}`);
          break;
        }

        case InstructionType.CSINC: {
          const condExpr = decoded.cond === ConditionCode.EQ ? "flagZ" : "!flagZ";
          lines.push(`${indent}x[${decoded.rd}] = (${condExpr}) ? ${regExpr(decoded.rn)} : (${regExpr(decoded.rm)} + 1n); // ${decoded.disassembly}`);
          break;
        }

        case InstructionType.BL: {
          const targetHex = `0x${(pc + decoded.offsetBytes).toString(16).padStart(8, "0")}`;
          lines.push(`${indent}x[30] = 0x${(pc + 4).toString(16)}n; // ${decoded.disassembly} -> call ${targetHex}`);
          break;
        }

        case InstructionType.RET:
          lines.push(`${indent}// ${decoded.disassembly} (return to LR/X30)`);
          break;

        case InstructionType.B_COND: {
          const targetPC = pc + decoded.offsetBytes;
          const targetHex = `0x${targetPC.toString(16).padStart(8, "0")}`;

          // Backwards branch: close the reconstructed do-while loop
          if (targetPC <= pc) {
            indentLevel = Math.max(1, indentLevel - 1);
            const condExpr = decoded.cond === ConditionCode.NE ? "!flagZ" : "flagZ";
            lines.push(`${getIndent()}} while (${condExpr}); // ${decoded.disassembly} -> ${targetHex}`);
          } else {
            lines.push(`${indent}// Conditional forward jump: ${decoded.disassembly} -> ${targetHex}`);
          }
          break;
        }

        case InstructionType.B: {
          const targetPC = pc + decoded.offsetBytes;
          const targetHex = `0x${targetPC.toString(16).padStart(8, "0")}`;
          if (targetPC <= pc && loopStarts.has(targetPC)) {
            indentLevel = Math.max(1, indentLevel - 1);
            lines.push(`${getIndent()}} while (!flagZ); // ${decoded.disassembly} -> ${targetHex}`);
          } else {
            lines.push(`${indent}// Jump: ${decoded.disassembly} -> ${targetHex}`);
          }
          break;
        }

        case InstructionType.SVC:
          lines.push(`${indent}// Supervisor Call (${decoded.disassembly}): check X8 syscall (64=write, 93/94=exit, 124=yield)`);
          lines.push(`${indent}if (x[8] === 124n) { x[0] = 0n; }`);
          lines.push(`${indent}if (x[8] === 93n || x[8] === 94n) return Number(x[0]);`);
          break;

        default:
          lines.push(`${indent}// ${decoded.disassembly} (${hexPC})`);
          break;
      }
    }

    lines.push("  return Number(x[0]);");
    lines.push("}");

    const fullSource = lines.join("\n") + "\n";
    if (writeFiles) {
      fs.mkdirSync("out", { recursive: true });
      fs.writeFileSync("out/fib_recompiled.js", fullSource);
      console.log(`[Static Recompiler] Successfully generated native source: out/fib_recompiled.js`);
    }

    return fullSource;
  }
}

// ----------------------------------------------------------------------
// BENCHMARK: Interpreter vs. Statically Recompiled AOT
// ----------------------------------------------------------------------
async function benchmark() {
  const recompiler = new StaticRecompiler("bin/fib.elf");
  recompiler.recompile(true);

  const { runNative } = await import("../out/fib_recompiled.js");

  const ITERATIONS = 10000;
  console.log(`\n==========================================================================================`);
  console.log(`            PERFORMANCE BENCHMARK: Interpreter vs. Static Recompilation (AOT)             `);
  console.log(`            Running ${ITERATIONS.toLocaleString()} iterations of Fibonacci(10)            `);
  console.log(`==========================================================================================`);

  // 1. Benchmark Interpreter
  console.log(`Running in Mini-QEMU Interpreter (Fetch -> Decode -> Execute loop)...`);
  const emulator = new MiniQEMU();
  emulator.loadElf("bin/fib.elf");

  const startInterp = performance.now();
  let interpResult = 0;
  for (let i = 0; i < ITERATIONS; i++) {
    // Reset CPU for next run
    emulator.cpu.pc = 0x00400000n;
    emulator.cpu.halted = false;
    emulator.cycleCount = 0;
    interpResult = emulator.run(1000, false); // false = non-verbose
  }
  const endInterp = performance.now();
  const interpDurationMs = endInterp - startInterp;

  // 2. Benchmark Statically Recompiled Native Code (genuinely lifted from fib.elf)
  console.log(`Running in Statically Recompiled Native Code (runNative lifted from fib.elf)...`);
  const startAOT = performance.now();
  let aotResult = 0;
  for (let i = 0; i < ITERATIONS; i++) {
    aotResult = runNative();
  }
  const endAOT = performance.now();
  const aotDurationMs = endAOT - startAOT;

  console.log(`\n--- BENCHMARK RESULTS ---`);
  console.log(`Interpreter Result      : ${interpResult} in ${interpDurationMs.toFixed(2)} ms`);
  console.log(`Static Recompiled Result: ${aotResult} in ${aotDurationMs.toFixed(2)} ms`);
  console.log(`Speedup Factor          : ${(interpDurationMs / aotDurationMs).toFixed(1)}x FASTER with Static AOT!`);
  console.log(`==========================================================================================`);
}

if (typeof process !== "undefined" && process.argv && process.argv[1]?.endsWith("static_recompiler.js")) {
  benchmark();
}
